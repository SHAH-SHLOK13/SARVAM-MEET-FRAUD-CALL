// CallShield Incident Report Modal Component

import { esc, fmtDateTime } from '../formatters.js';
import { api } from '../api.js';

const VERDICT_TEXT = { likely_scam: 'LIKELY SCAM', awareness_or_joke: 'AWARENESS / JOKE / TEST', benign: 'BENIGN', unclear: 'UNCLEAR' };
const VERDICT_CLS = { likely_scam: 'danger', awareness_or_joke: 'ok', benign: 'ok', unclear: 'warn' };

/** AI call summary (verdict, headline, summary, timeline, advice) as HTML; shared with the vision panel. */
export function summaryHtml(s) {
  if (!s) return '<div class="muted">Generating summary with Sarvam AI…</div>';
  if (s.error) return `<div class="muted">Summary unavailable: ${esc(s.error)}</div>`;
  return `
    <div class="summary-headline"><span class="badge badge-${VERDICT_CLS[s.verdict] || 'warn'}">${esc(VERDICT_TEXT[s.verdict] || s.verdict)}</span> <b>${esc(s.headline)}</b></div>
    <p class="summary-text">${esc(s.summary)}</p>
    ${(s.timeline || []).length ? `<ul class="summary-timeline">${s.timeline.map(t => `<li><code>${esc(t.time)}</code> ${esc(t.what)}</li>`).join('')}</ul>` : ''}
    ${s.advice ? `<div class="summary-advice"><b>Advice:</b> ${esc(s.advice)}</div>` : ''}
    <div class="muted small">Written by ${esc(s.model || 'Sarvam AI')} from the call ledger; the risk score itself is deterministic.</div>`;
}

export class ReportModal {
  constructor(containerId, onOpenChakshu) {
    this.container = document.getElementById(containerId);
    this.onOpenChakshu = onOpenChakshu;
    this.reportData = null;
    this.markdownText = '';
    this.activeTab = 'formatted'; // 'formatted' | 'markdown' | 'json'
  }

  async open(reportData, markdownText, sessionId) {
    this.reportData = reportData;
    this.markdownText = markdownText;
    this.sessionId = sessionId;
    this.activeTab = 'formatted';
    this.render();
    this.container.classList.remove('hidden');
    document.body.classList.add('modal-open');
  }

  setSummary(summary, markdownText) {
    if (!this.reportData) return;
    this.reportData.call_summary = summary;
    if (markdownText) this.markdownText = markdownText;
    if (!this.container.classList.contains('hidden')) this.render();
  }

  _renderSummary(r) {
    const body = summaryHtml(r.call_summary);
    const frames = r.key_frames || [];
    const gallery = frames.length ? `
      <h3 class="section-heading">Screenshots of key moments (${frames.length})</h3>
      <div class="keyframe-grid">
        ${frames.map(f => `
          <a class="keyframe" href="${api.frameUrl(r.session_id, f.frame_id)}" target="_blank" rel="noopener">
            <img src="${api.frameUrl(r.session_id, f.frame_id)}" alt="${esc(f.reason)}" loading="lazy" />
            <div class="keyframe-cap"><code>${esc(f.time ? fmtDateTime(new Date(f.time).getTime()) : '')}</code> · risk ${esc(f.risk_index ?? '–')}<br>${esc(f.reason)}</div>
          </a>`).join('')}
      </div>` : '<h3 class="section-heading">Screenshots of key moments</h3><div class="muted">None taken (risk never rose to HIGH, no chat was flagged, nothing was shown on video).</div>';
    return `<h3 class="section-heading">Call Summary</h3><div class="summary-card">${body}</div>${gallery}`;
  }

  close() {
    this.container.classList.add('hidden');
    document.body.classList.remove('modal-open');
  }

  render() {
    if (!this.reportData) return;
    const r = this.reportData;
    const peak = r.peak_assessment || {};

    this.container.innerHTML = `
      <div class="modal-backdrop" id="reportBackdrop"></div>
      <div class="modal-card modal-large" role="dialog" aria-modal="true" aria-labelledby="reportTitle">
        <div class="modal-header">
          <div>
            <div class="modal-pretitle">Security Incident Ledger Report</div>
            <h2 id="reportTitle" class="modal-title">Incident Report: ${esc(r.session_id)}</h2>
          </div>
          <div class="modal-header-actions">
            <button class="btn btn-sm btn-accent" id="reportToChakshuBtn">Report to Chakshu ↗</button>
            <button class="icon-button" id="reportCloseBtn" title="Close" aria-label="Close">✕</button>
          </div>
        </div>

        <div class="tab-bar">
          <button class="tab-btn ${this.activeTab === 'formatted' ? 'active' : ''}" data-tab="formatted">Executive Summary</button>
          <button class="tab-btn ${this.activeTab === 'markdown' ? 'active' : ''}" data-tab="markdown">Markdown Document</button>
          <button class="tab-btn ${this.activeTab === 'json' ? 'active' : ''}" data-tab="json">Raw JSON Ledger</button>
        </div>

        <div class="modal-body">
          <div class="alert-box warn-box">
            <div class="alert-icon">⚠️</div>
            <div>
              <b>Non-Filing Legal Notice:</b> ${esc(r.disclaimer || 'Generated by CallShield proof of concept. NOT submitted to any authority. Risk index is a heuristic score, not a probability.')}
            </div>
          </div>

          ${this.activeTab === 'formatted' ? this._renderFormatted(r, peak) : ''}
          ${this.activeTab === 'markdown' ? this._renderMarkdown() : ''}
          ${this.activeTab === 'json' ? this._renderJson(r) : ''}
        </div>

        <div class="modal-footer">
          <div class="footer-left">
            <span class="muted small">Generated at ${esc(r.generated_at || '–')}</span>
          </div>
          <div class="footer-right">
            <button class="btn btn-ghost" id="copyReportBtn">Copy Document</button>
            <button class="btn btn-secondary" id="downloadMdBtn">Download Markdown (.md)</button>
            <button class="btn btn-primary" id="reportDoneBtn">Done</button>
          </div>
        </div>
      </div>
    `;

    this._bindEvents();
  }

  _renderFormatted(r, peak) {
    return `
      <div class="report-formatted">
        ${this._renderSummary(r)}
        <div class="report-metric-row">
          <div class="report-metric-card">
            <div class="metric-label">Peak Risk Level</div>
            <div class="metric-val risk-text-${peak.risk_level || 'normal'}">${esc((peak.risk_level || 'Normal').toUpperCase())}</div>
            <div class="metric-sub">Score: ${peak.risk_index ?? 0}/100</div>
          </div>
          <div class="report-metric-card">
            <div class="metric-label">Evidence Strength</div>
            <div class="metric-val">${esc(peak.evidence_strength || 'none')}</div>
            <div class="metric-sub">Active Patterns: ${(peak.patterns || []).join(', ') || 'None'}</div>
          </div>
          <div class="report-metric-card">
            <div class="metric-label">Call Started</div>
            <div class="metric-val text-sm">${esc(r.started_at ? fmtDateTime(new Date(r.started_at).getTime()) : '–')}</div>
            <div class="metric-sub">Inference: ${(r.inference_modes_seen || []).join(', ') || '–'}</div>
          </div>
          <div class="report-metric-card">
            <div class="metric-label">Official Status</div>
            <div class="metric-val text-sm ${r.official_complaint_submitted ? 'text-ok' : 'text-muted'}">
              ${r.official_complaint_submitted ? 'Filed' : 'Unfiled / Draft'}
            </div>
            <div class="metric-sub">Not submitted to authorities</div>
          </div>
        </div>

        <h3 class="section-heading">Recorded Evidence Items (${(r.evidence || []).length})</h3>
        <div class="report-evidence-list">
          ${(r.evidence || []).length === 0 ? '<p class="muted">No evidence recorded.</p>' : ''}
          ${(r.evidence || []).map(ev => `
            <div class="report-ev-item ${ev.retracted ? 'retracted' : ''}">
              <div class="report-ev-header">
                <span class="badge ${ev.retracted ? 'badge-muted' : 'badge-danger'}">${esc(ev.category)}</span>
                <span class="tag">${esc(ev.modality)}</span>
                ${ev.mock ? '<span class="tag badge-warn">SIMULATED / MOCK</span>' : ''}
                ${ev.rules && ev.rules.length ? `<span class="tag">${esc(ev.rules.join(', '))}</span>` : ''}
                <span class="time">${esc(ev.time ? fmtDateTime(new Date(ev.time).getTime()) : '–')}</span>
                ${ev.retracted ? `<span class="badge badge-warn">RETRACTED: ${esc(ev.retracted)}</span>` : ''}
              </div>
              <div class="report-ev-quote">“${esc(ev.quote)}”</div>
            </div>
          `).join('')}
        </div>

        <h3 class="section-heading">Call Safety &amp; Policy Actions (${(r.actions || []).length})</h3>
        <div class="report-actions-table">
          <table class="data-table">
            <thead>
              <tr><th>Timestamp</th><th>Action Type</th><th>Status</th><th>Source</th></tr>
            </thead>
            <tbody>
              ${(r.actions || []).length === 0 ? '<tr><td colspan="4" class="muted">No policy actions executed.</td></tr>' : ''}
              ${(r.actions || []).map(a => `
                <tr>
                  <td>${esc(a.time ? fmtDateTime(new Date(a.time).getTime()) : '–')}</td>
                  <td><b>${esc(a.action_type)}</b></td>
                  <td><span class="status-pill status-${esc(a.status)}">${esc(a.status)}</span></td>
                  <td>${esc(a.source)}</td>
                </tr>
              `).join('')}
            </tbody>
          </table>
        </div>

        <h3 class="section-heading">Official Reporting Guidance</h3>
        <ul class="report-guidance-list">
          ${(r.reporting_guidance || []).map(g => `<li>${esc(g)}</li>`).join('')}
        </ul>
      </div>
    `;
  }

  _renderMarkdown() {
    return `
      <div class="report-code-wrap">
        <pre class="report-markdown-preview"><code>${esc(this.markdownText)}</code></pre>
      </div>
    `;
  }

  _renderJson(r) {
    return `
      <div class="report-code-wrap">
        <pre class="report-json-preview"><code>${esc(JSON.stringify(r, null, 2))}</code></pre>
      </div>
    `;
  }

  _bindEvents() {
    const backdrop = document.getElementById('reportBackdrop');
    const closeBtn = document.getElementById('reportCloseBtn');
    const doneBtn = document.getElementById('reportDoneBtn');
    const chakshuBtn = document.getElementById('reportToChakshuBtn');

    if (backdrop) backdrop.onclick = () => this.close();
    if (closeBtn) closeBtn.onclick = () => this.close();
    if (doneBtn) doneBtn.onclick = () => this.close();

    if (chakshuBtn) {
      chakshuBtn.onclick = () => {
        this.close();
        if (this.onOpenChakshu) this.onOpenChakshu();
      };
    }

    const tabBtns = this.container.querySelectorAll('.tab-btn');
    tabBtns.forEach(btn => {
      btn.onclick = () => {
        this.activeTab = btn.dataset.tab;
        this.render();
      };
    });

    const copyBtn = document.getElementById('copyReportBtn');
    if (copyBtn) {
      copyBtn.onclick = async () => {
        const textToCopy = this.activeTab === 'json' ? JSON.stringify(this.reportData, null, 2) : this.markdownText;
        try {
          await navigator.clipboard.writeText(textToCopy);
          const orig = copyBtn.textContent;
          copyBtn.textContent = 'Copied!';
          setTimeout(() => { copyBtn.textContent = orig; }, 2000);
        } catch (err) {
          console.warn('Copy failed:', err);
        }
      };
    }

    const downloadBtn = document.getElementById('downloadMdBtn');
    if (downloadBtn) {
      downloadBtn.onclick = () => {
        const blob = new Blob([this.markdownText], { type: 'text/markdown;charset=utf-8' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `callshield-incident-${this.sessionId || 'session'}.md`;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
      };
    }
  }
}

